const STOP = new Set(['и', 'в', 'на', 'с', 'по', 'для', 'не', 'или', 'при', 'до', 'от', 'о', 'к', 'из', 'а', 'же', 'это']);
// Грубый стемминг: обрезка окончаний — достаточно для поиска по коротким фрагментам без внешних библиотек.
export const tokenize = (s) => String(s).toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я0-9]+/)
  .filter((w) => w.length > 1 && !STOP.has(w))
  .map((w) => (w.length > 5 ? w.slice(0, w.length - 2) : w));

function buildIndex(docs) {
  const tf = docs.map((d) => {
    const m = new Map();
    for (const t of tokenize(`${d.title} ${d.title} ${d.text}`)) m.set(t, (m.get(t) ?? 0) + 1);
    return m;
  });
  const df = new Map();
  for (const m of tf) for (const t of m.keys()) df.set(t, (df.get(t) ?? 0) + 1);
  const len = tf.map((m) => [...m.values()].reduce((a, b) => a + b, 0));
  const avg = len.reduce((a, b) => a + b, 0) / (len.length || 1);
  return { tf, df, len, avg, n: docs.length };
}
const INDEX = buildIndex(DOCS);

/** BM25-поиск по локальной базе знаний. */
export function search(query, k = 5) {
  const q = tokenize(query);
  const { tf, df, len, avg, n } = INDEX;
  return DOCS.map((d, i) => {
    let s = 0;
    for (const t of q) {
      const f = tf[i].get(t);
      if (!f) continue;
      const idf = Math.log(1 + (n - df.get(t) + 0.5) / (df.get(t) + 0.5));
      s += idf * (f * 2.2) / (f + 1.2 * (0.25 + 0.75 * len[i] / avg));
    }
    return { ...d, score: +s.toFixed(3) };
  }).filter((d) => d.score > 0).sort((a, b) => b.score - a.score).slice(0, k);
}

